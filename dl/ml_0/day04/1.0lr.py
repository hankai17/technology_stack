# -*- coding:utf-8 -*-
"""
逻辑回归在 iris 上的决策边界：
只取前两个特征(花萼长 / 花萼宽)做二维可视化，训练后把整个平面按预测类别染色，
直观看到"线性模型的分界面就是直线(高维下是超平面)"。
"""

# print(__doc__) 是 sklearn 官方示例的惯例：把文件顶部的 docstring 打到屏幕上，
# 相当于脚本一运行先打印一段说明
print(__doc__)

import numpy as np
import matplotlib.pyplot as plt
from sklearn import linear_model, datasets


# 载入 sklearn 自带的 iris(鸢尾花) 数据集：150 条样本，3 类(setosa/versicolor/virginica)，每类 50 条
iris = datasets.load_iris()
# 只取前两个特征(花萼长 sepal length、花萼宽 sepal width)，这样能画在二维平面上
# 剩下的两个特征(花瓣长、花瓣宽)被丢掉了——这里画图优先，不是为了追求分类效果
X = iris.data[:, :2]
Y = iris.target

# 网格步长：后面要在坐标平面上撒点预测，步长越小决策边界越平滑，代价是预测的点越多
h = .02

# 逻辑回归：C 是正则化强度的倒数(C = 1/λ)，
#   C 越小 → 正则越强 → 权重被压得更小 → 边界更"保守"、更平滑
#   C = 1e5 基本等于不正则化，让决策边界尽量贴合训练数据
# 三分类时 sklearn 用多项逻辑回归(softmax)，等价于 3 个线性打分函数取最大
logreg = linear_model.LogisticRegression(C=1e5)

# 在 150 条样本的 2 个特征上拟合，学到的其实是 3 组 (w, b)
logreg.fit(X, Y)
# 数据结构（拟合后，实测）：
#   logreg.coef_  -> np.ndarray shape (3, 2)：3 个类别 × 2 个特征的权重 w
#       （3 分类 softmax 下每类一组 w，决定"这类相对其他类的分界面斜率"）
#   logreg.intercept_ -> np.ndarray shape (3,)：每类的偏置 b
#   预测时对每个点算 3 个 z_c = w_c·x + b_c，再用 softmax 归一化成概率，取最大者当类别
#   实测 coef_ 前几列：
#     setosa(类0)     的 w 在 sepal length 上很负、sepal width 上很负 → 和另外两类分得开
#   注意：只用了 2 个特征，setosa 能完美分开，但 versicolor/virginica 这两类在 sepal 两维上重叠较多，
#   所以图上会看到一片"混色"区域——这正是原书"只用前两个特征是为了可视化"的代价


# 先把要画的范围定出来：取两个特征各自的最小/最大值，再向外扩 0.5 留点白边
x_min, x_max = X[:, 0].min() - .5, X[:, 0].max() + .5
y_min, y_max = X[:, 1].min() - .5, X[:, 1].max() + .5
# np.meshgrid 生成网格：xx / yy 都是同形状的二维数组，
#   xx 存每个格点的横坐标，yy 存纵坐标——合起来就是密铺整个平面的一堆坐标点
xx, yy = np.meshgrid(np.arange(x_min, x_max, h), np.arange(y_min, y_max, h))
# np.c_[xx.ravel(), yy.ravel()] 把网格摊平成 (n_points, 2) 的坐标表，逐点送进模型预测类别
# 这一步就是"用训练好的模型把整张图逐像素染色"的本质：对网格点做批量预测
Z = logreg.predict(np.c_[xx.ravel(), yy.ravel()])


# 预测结果是长度 n_points 的一维数组，还原回网格形状才能和 xx / yy 对上画成图
Z = Z.reshape(xx.shape)
plt.figure(1, figsize=(4, 3))
# pcolormesh 用色块铺满网格，不同类别不同颜色 —— 这就是模型的"决策区域"
plt.pcolormesh(xx, yy, Z, cmap=plt.cm.Paired)


# 再把真实样本点画上去(黑边描出来)，看有多少点落错了颜色区域
plt.scatter(X[:, 0], X[:, 1], c=Y, edgecolors='k', cmap=plt.cm.Paired)
plt.xlabel('Sepal length')
plt.ylabel('Sepal width')

# 坐标轴范围收紧到网格范围，并去掉刻度数字，只留画面
plt.xlim(xx.min(), xx.max())
plt.ylim(yy.min(), yy.max())
plt.xticks(())
plt.yticks(())

# 原书用 plt.show() 弹窗显示；在没有图形界面的环境(服务器 / 容器)下它是空操作，
# 所以改成保存成图片文件，方便直接查看结果
plt.savefig('1.0.png', dpi=150)
print("saved 1.0.png")

