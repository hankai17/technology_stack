# sigmoid:
#   sigmoid 用于压缩到 0-1，是因为逻辑回归解决的是二分类问题，输出需要直接对应 “属于正类的概率”
#   比如 sigmoid 算出来 0.8，就表示这个样本符合 “p=0.8 的伯努利分布”—— 有 80% 概率取 1，20% 取 0
#   逻辑回归就是用 sigmoid 把线性输出转成伯努利的 p，再基于这个 p 写似然函数，去拟合样本里真实的 0 和 1。

# 似然函数
#   “似然” 意思是 “看起来像”，就是在已知样本结果的情况下，去衡量不同参数值让这个样本出现的可能性有多大
#   eg: 抛硬币连续抛 8 次正 似然估计出的 p=1 比理想的 0.5 更 “合理”
#   eg: 抛硬币续抛 +00 次 正反各占一般 似然估计出的 p=0.5 即理想的 0.5  此为大数定律

#似然函数 L(p) = C(n,k) p^k*(1-p)^(n-k)，这里p是自变量，L(p)是因变量
#   L(p) 仅仅是关于p的一元函数。自变量是p，输出 L(p) 是因变量
#   eg: L(p) = 120 * p^7(1-p)^3   单纯看函数求导求极值的话 p 取何值时 能确保 L (p) 最大？  
#       可推出案例 抛硬币一共 n=10 次，实实在在观测看到：正面 k=7 次，反面 n-k=3 次。 则最大值是p为0.7
#   我们对 L (p) 求导找最大值，对应的 p 就是极大似然估计值 —— 它不是直接逼近理想概率，而是当样本量足够大时，这个估计值会天然向真实的理想概率收敛，这是大数定律在背后起作用。
#   似然函数是拿到样本后 “反推”(后验) 最可能的参数，属于从结果倒推原因的后验思路；等参数用极大似然估计定下来，再去预测新样本时，就是用固定参数的模型 “正推” 概率，这时候就是先验代入的过程了
#   
#   我们希望似然函数的结果越大越好 因为最大就能说明越贴近实验数据 这个就叫做最大似然
#       逻辑回归用的是最大似然估计，希望真实样本出现的概率最大，取负对数后就变成了最小化损失函数，这样梯度下降才能派上用场

# 损失函数
# 公式里每一项是 [σ(x⁽ⁱ⁾θ)-y⁽ⁱ⁾]・xⱼ⁽ⁱ⁾，前半部分 σ(...) - y⁽ⁱ⁾是第 i 个样本的预测误差，后半部分 xⱼ⁽ⁱ⁾是该样本第 j 个特征的取值。两者相乘，就是用这个特征的数值去 “加权” 误差 —— 特征值 xⱼ⁽ⁱ⁾越大，同样的误差对第 j 个权重 θⱼ的调整力度就越大。所有样本的这个乘积加起来除以 n，就是整体上 θⱼ要调整的幅度，完全是按特征的数值大小来分配误差的修正权重。
